package corpus

import (
	"fmt"
	"sort"
	"strings"

	"github.com/TurlaFSB/logshield/internal/engine"
)

// Targets are the project's measurable quality bars (docs/ROADMAP.md).
type Targets struct {
	// MaxMisses is the number of in-scope attack entries that may escape.
	MaxMisses int
	// MaxFalsePositiveRate is the largest tolerated blocking rate on benign traffic.
	MaxFalsePositiveRate float64
}

// DefaultTargets are 0 misses and under 0.1% false positives.
var DefaultTargets = Targets{MaxMisses: 0, MaxFalsePositiveRate: 0.001}

// Report is a complete evaluation, ready to render.
type Report struct {
	Bypass    []Outcome
	Benign    []Outcome
	Generated []Outcome
	GenSeed   uint64
	Targets   Targets
	Rules     []engine.RuleInfo
}

// Markdown renders the report. It is deterministic: no timestamps.
func (r Report) Markdown() string {
	var b strings.Builder
	bs, ns, gs := Summarize(r.Bypass), Summarize(r.Benign), Summarize(r.Generated)

	b.WriteString("# Evaluation report\n\n")
	b.WriteString("Generated by `make eval` from the corpora in `corpus/`. Do not edit by hand.\n\n")

	b.WriteString("## Targets\n\n| Target | Required | Measured | Status |\n|---|---|---|---|\n")
	missStatus := status(bs.Misses <= r.Targets.MaxMisses && bs.Failed == 0)
	fmt.Fprintf(&b, "| Attack entries not blocked | %d | %d of %d | %s |\n", r.Targets.MaxMisses, bs.Misses, bs.Total, missStatus)

	benignN := ns.Total + gs.Total
	benignFP := ns.FalsePositives + gs.FalsePositives
	upper := WilsonUpper(benignFP, benignN)
	fpStatus := status(upper <= r.Targets.MaxFalsePositiveRate && ns.Failed+gs.Failed == 0)
	fmt.Fprintf(&b, "| Benign requests blocked (95%% upper bound) | < %.2f%% | %d of %d (< %.4f%%) | %s |\n",
		r.Targets.MaxFalsePositiveRate*100, benignFP, benignN, upper*100, fpStatus)
	b.WriteString("\n")
	b.WriteString("A zero-count result does not prove a zero rate; the 95% upper bound (Wilson score) is the honest figure. ")
	b.WriteString("It shrinks as the benign corpus grows.\n\n")

	b.WriteString("## Datasets\n\n| Dataset | Entries | Malicious | Suspicious | Clean | Unexpected results |\n|---|---|---|---|---|---|\n")
	for _, row := range []struct {
		name string
		s    Stats
	}{{"bypass (hand-curated)", bs}, {"benign (hand-curated)", ns}, {fmt.Sprintf("benign (generated, seed %d)", r.GenSeed), gs}} {
		fmt.Fprintf(&b, "| %s | %d | %d | %d | %d | %d |\n", row.name, row.s.Total, row.s.Malicious, row.s.Suspicious, row.s.Clean, row.s.Failed)
	}
	b.WriteString("\n")

	b.WriteString("## Bypass corpus by technique\n\n| Class | Entries | Source types | Blocked or flagged as expected |\n|---|---|---|---|\n")
	classes, groups := ByClass(r.Bypass)
	for _, c := range classes {
		g := groups[c]
		pass := 0
		types := map[string]int{}
		for _, o := range g {
			if o.Pass {
				pass++
			}
			types[o.Entry.Source.Type]++
		}
		fmt.Fprintf(&b, "| %s | %d | %s | %d/%d |\n", c, len(g), joinCounts(types), pass, len(g))
	}
	b.WriteString("\n")

	b.WriteString("## Rule coverage\n\nHow many corpus entries each rule fired on. A rule with no entries is untested.\n\n| Rule | Name | Severity | Bypass | Benign |\n|---|---|---|---|---|\n")
	for _, ri := range r.Rules {
		fmt.Fprintf(&b, "| %s | %s | %s | %d | %d |\n", ri.ID, ri.Name, ri.Severity, fired(r.Bypass, ri.ID), fired(append(append([]Outcome{}, r.Benign...), r.Generated...), ri.ID))
	}
	b.WriteString("\n")

	b.WriteString("## Provenance\n\n| Source type | Meaning | Bypass entries |\n|---|---|---|\n")
	counts := map[string]int{}
	for _, o := range r.Bypass {
		counts[o.Entry.Source.Type]++
	}
	fmt.Fprintf(&b, "| %s | quoted from a public write-up, hosts replaced with reserved names | %d |\n", SourcePublic, counts[SourcePublic])
	fmt.Fprintf(&b, "| %s | constructed to exercise a documented technique | %d |\n", SourceDerived, counts[SourceDerived])
	fmt.Fprintf(&b, "| %s | written by this project (regressions, look-alikes) | %d |\n", SourceProject, counts[SourceProject])
	b.WriteString("\nPublic sources used:\n\n")
	seen := map[string]bool{}
	var refs []string
	for _, o := range r.Bypass {
		if u := o.Entry.Source.URL; u != "" && !seen[u] {
			seen[u] = true
			refs = append(refs, fmt.Sprintf("- [%s](%s)", o.Entry.Source.Ref, u))
		}
	}
	sort.Strings(refs)
	b.WriteString(strings.Join(refs, "\n") + "\n\n")

	b.WriteString("## Scope and limits\n\n")
	b.WriteString("- Measured against the engine's own model of Log4j; real-Log4j validation is reported separately in docs/lab-report.md.\n")
	b.WriteString("- The benign corpus is synthetic plus hand-written look-alikes, not production traffic. Expect the real false-positive rate to differ; run the proxy in monitor mode first.\n")
	b.WriteString("- Suspicious verdicts (surfaced, not blocked) on benign look-alikes are reported above and are not counted as false positives.\n")
	b.WriteString("- Payloads are inert: reserved names only (RFC 2606, 5737).\n")
	return b.String()
}

func status(ok bool) string {
	if ok {
		return "pass"
	}
	return "**FAIL**"
}

func fired(outcomes []Outcome, id engine.RuleID) int {
	n := 0
	for _, o := range outcomes {
		if o.Verdict.Has(id) {
			n++
		}
	}
	return n
}

func joinCounts(m map[string]int) string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	parts := make([]string, len(keys))
	for i, k := range keys {
		parts[i] = fmt.Sprintf("%s %d", k, m[k])
	}
	return strings.Join(parts, ", ")
}
