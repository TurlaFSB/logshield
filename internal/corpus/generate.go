// special holds text fragments that stress the decoder and resolver without
// being attacks: characters that look like encodings or lookups, but are not.
var special = []string{
	"$", "$5", "{", "}", "{}", "{{name}}", "%", "100%", "50%25", "%20", "%E2%9C%93", "a%2Fb", "&amp;", "&lt;", "&#169;", "&#x1F600;",
	"\\n", "\\u00e9", "\\\\", "C:\\Users\\x", "::", "a:b", "http://example.com/a?b=c&d=e", "ldap://ldap.example.com:389/dc=example,dc=com",
	"jndi", "JNDI", "jndi:", "java naming", "${name}", "${user.name}", "${a-b_c}", "${count} items", "${HOME}/bin", "${PORT:8080}",
	"${var:-default}", "${1}", "${#arr}", "${arr[@]}", "$HOME", "$(date)", "`id`", "<script>", "'; --", "../..", "%2e%2e%2f",
	"\U0001F600", "caf\u00e9", "Привет", "你好", "\u200b", "a\tb", "x=1;y=2", "t.co/abc",
}

// Generate returns n deterministic benign requests built from realistic parts.
// Every entry expects a clean verdict.
func Generate(n int, seed uint64) []Entry {
	// Deterministic test data, not a security boundary.
	rng := rand.New(rand.NewPCG(seed, seed^0x9e3779b97f4a7c15)) //nolint:gosec // G404: reproducible corpus, not secrets
	g := &gen{rng: rng}
	out := make([]Entry, 0, n)
	for i := 0; i < n; i++ {
		out = append(out, Entry{
			ID:      fmt.Sprintf("gen-%06d", i),
			Class:   "generated-benign",
			Source:  Source{Type: SourceProject, Ref: "generated by corpus.Generate"},
			Request: g.request(),
			Expect:  Expect{Decision: "clean"},
			Dataset: "generated",
		})
	}
	return out
}

type gen struct{ rng *rand.Rand }

func (g *gen) pick(s []string) string { return s[g.rng.IntN(len(s))] }
func (g *gen) word() string           { return g.pick(words) }

func (g *gen) phrase() string {
	n := 1 + g.rng.IntN(6)
	parts := make([]string, 0, n)
	for i := 0; i < n; i++ {
		switch g.rng.IntN(8) {
		case 0:
			parts = append(parts, g.pick(special))
		default:
			parts = append(parts, g.word())
		}
	}
	return strings.Join(parts, " ")
}

func (g *gen) blob() []byte {
	b := make([]byte, 4+g.rng.IntN(60))
	for i := range b {
		b[i] = byte(g.rng.IntN(256))
	}
	return b
}

func (g *gen) token() string {
	switch g.rng.IntN(4) {
	case 0:
		return base64.StdEncoding.EncodeToString(g.blob())
	case 1:
		return base64.RawURLEncoding.EncodeToString(g.blob())
	case 2:
		return fmt.Sprintf("%x", g.blob())
	default:
		return g.word() + "-" + fmt.Sprint(g.rng.IntN(100000))
	}
}

func (g *gen) path() string {
	n := 1 + g.rng.IntN(4)
	segs := make([]string, n)
	for i := range segs {
		switch g.rng.IntN(5) {
		case 0:
			segs[i] = fmt.Sprint(g.rng.IntN(1000000))
		case 1:
			segs[i] = url.PathEscape(g.phrase())
		default:
			segs[i] = g.word()
		}
	}
	return "/" + strings.Join(segs, "/")
}

func (g *gen) query() string {
	n := g.rng.IntN(5)
	if n == 0 {
		return ""
	}
	pairs := make([]string, n)
	for i := range pairs {
		v := g.phrase()
		if g.rng.IntN(3) == 0 {
			v = g.token()
		}
		pairs[i] = g.word() + "=" + url.QueryEscape(v)
	}
	return "?" + strings.Join(pairs, "&")
}

func (g *gen) jsonBody() string {
	m := map[string]any{}
	for i, n := 0, 1+g.rng.IntN(6); i < n; i++ {
		switch g.rng.IntN(5) {
		case 0:
			m[g.word()] = g.rng.IntN(100000)
		case 1:
			m[g.word()] = []string{g.phrase(), g.phrase()}
		case 2:
			m[g.word()] = map[string]any{g.word(): g.phrase(), g.word(): g.rng.Float64()}
		case 3:
			m[g.word()] = g.token()
		default:
			m[g.word()] = g.phrase()
		}
	}
	b, _ := json.Marshal(m) // escapes <, >, & as \u003c etc., like many servers
	return string(b)
}

func (g *gen) body() (contentType, body string) {
	switch g.rng.IntN(5) {
	case 0:
		return "application/json", g.jsonBody()
	case 1:
		pairs := make([]string, 1+g.rng.IntN(4))
		for i := range pairs {
			pairs[i] = g.word() + "=" + url.QueryEscape(g.phrase())
		}
		return "application/x-www-form-urlencoded", strings.Join(pairs, "&")
	case 2:
		return "text/plain", g.phrase() + "\n" + g.phrase()
	case 3:
		return "text/xml", "<" + g.word() + ">" + g.phrase() + "</" + g.word() + ">"
	default:
		b := "--GEN\r\nContent-Disposition: form-data; name=\"" + g.word() + "\"; filename=\"" + g.word() + ".txt\"\r\n\r\n" + g.phrase() + "\r\n--GEN--\r\n"
		return "multipart/form-data; boundary=GEN", b
	}
}

func (g *gen) request() Request {
	r := Request{Method: g.pick([]string{http.MethodGet, http.MethodGet, http.MethodGet, http.MethodPost, http.MethodPut, http.MethodDelete, http.MethodPatch, http.MethodHead, http.MethodOptions})}
	r.Target = g.path() + g.query()
	r.Headers = [][2]string{{"Host", g.word() + ".example.com"}, {"User-Agent", g.pick(userAgents)}}
	add := func(n, v string) { r.Headers = append(r.Headers, [2]string{n, v}) }
	if g.rng.IntN(2) == 0 {
		add("Accept-Language", "en-US,en;q=0.9")
	}
	if g.rng.IntN(2) == 0 {
		add("Referer", "https://"+g.word()+".example.org"+g.path()+g.query())
	}
	if g.rng.IntN(2) == 0 {
		cs := make([]string, 1+g.rng.IntN(5))
		for i := range cs {
			cs[i] = g.word() + "=" + g.token()
		}
		add("Cookie", strings.Join(cs, "; "))
	}
	switch g.rng.IntN(6) {
	case 0:
		add("Authorization", "Basic "+base64.StdEncoding.EncodeToString([]byte(g.word()+":"+g.phrase())))
	case 1:
		add("Authorization", "Bearer "+g.token()+"."+g.token()+"."+g.token())
	case 2:
		add("Authorization", "Bearer "+base64.RawURLEncoding.EncodeToString([]byte(`{"alg":"RS256"}`))+"."+
			base64.RawURLEncoding.EncodeToString([]byte(`{"sub":"`+g.word()+`","scope":"`+g.phrase()+`"}`))+"."+g.token())
	}
	for i, n := 0, g.rng.IntN(4); i < n; i++ {
		add("X-"+capitalize(g.word())+"-"+capitalize(g.word()), g.phrase())
	}
	if r.Method == http.MethodPost || r.Method == http.MethodPut || r.Method == http.MethodPatch {
		ct, body := g.body()
		add("Content-Type", ct)
		r.Body = body
	}
	return r
}

func capitalize(s string) string { return strings.ToUpper(s[:1]) + s[1:] }
